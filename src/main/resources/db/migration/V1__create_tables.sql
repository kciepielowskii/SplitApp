
-- ==========================================
-- 1. USERS
-- ==========================================

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       first_name VARCHAR(50) NOT NULL,
                       last_name VARCHAR(50) NOT NULL,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password VARCHAR(120) NOT NULL,
                       created_at TIMESTAMP NOT NULL
);

-- ==========================================
-- 2. GROUPS
-- ==========================================

CREATE TABLE expense_group (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               group_name VARCHAR(100) NOT NULL,
                               group_description VARCHAR(255),

                               user_id BIGINT NOT NULL,

                               created_at TIMESTAMP NOT NULL,

                               CONSTRAINT fk_group_creator
                                   FOREIGN KEY (user_id)
                                       REFERENCES users(id)
);

-- ==========================================
-- 3. GROUP MEMBERS
-- ==========================================

CREATE TABLE group_members (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               group_id BIGINT NOT NULL,
                               user_id BIGINT NOT NULL,

                               role VARCHAR(255) NOT NULL,
                               joined_at TIMESTAMP NOT NULL,

                               CONSTRAINT fk_group_member_group
                                   FOREIGN KEY (group_id)
                                       REFERENCES expense_group(id),

                               CONSTRAINT fk_group_member_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES users(id),

                               CONSTRAINT uk_group_member
                                   UNIQUE (group_id, user_id)
);

-- ==========================================
-- 4. EXPENSES
-- ==========================================

CREATE TABLE expenses (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          amount NUMERIC(10, 2) NOT NULL,
                          category VARCHAR(255) NOT NULL,
                          description VARCHAR(255),

                          group_id BIGINT NOT NULL,
                          paid_by_id BIGINT NOT NULL,

                          created_at TIMESTAMP NOT NULL,

                          CONSTRAINT fk_expense_group
                              FOREIGN KEY (group_id)
                                  REFERENCES expense_group(id),

                          CONSTRAINT fk_expense_paid_by
                              FOREIGN KEY (paid_by_id)
                                  REFERENCES users(id),

                          CONSTRAINT chk_expense_amount
                              CHECK (amount > 0)
);

-- ==========================================
-- 5. EXPENSE SPLITS
-- ==========================================

CREATE TABLE expense_splits (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                amount NUMERIC(10, 2) NOT NULL,

                                expense_id BIGINT NOT NULL,
                                user_id BIGINT NOT NULL,

                                CONSTRAINT fk_split_expense
                                    FOREIGN KEY (expense_id)
                                        REFERENCES expenses(id),

                                CONSTRAINT fk_split_user
                                    FOREIGN KEY (user_id)
                                        REFERENCES users(id),

                                CONSTRAINT uk_expense_split_user
                                    UNIQUE (expense_id, user_id),

                                CONSTRAINT chk_split_amount
                                    CHECK (amount > 0)
);

-- ==========================================
-- 6. PAYMENTS
-- ==========================================

CREATE TABLE payments (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          group_id BIGINT NOT NULL,
                          sender_id BIGINT NOT NULL,
                          receiver_id BIGINT NOT NULL,

                          amount NUMERIC(10, 2) NOT NULL,
                          paid_at TIMESTAMP NOT NULL,

                          CONSTRAINT fk_payment_group
                              FOREIGN KEY (group_id)
                                  REFERENCES expense_group(id),

                          CONSTRAINT fk_payment_sender
                              FOREIGN KEY (sender_id)
                                  REFERENCES users(id),

                          CONSTRAINT fk_payment_receiver
                              FOREIGN KEY (receiver_id)
                                  REFERENCES users(id),

                          CONSTRAINT chk_payment_amount
                              CHECK (amount > 0)
);
