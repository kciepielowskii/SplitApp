CREATE TABLE group_invitations (
                                   id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   group_id      bigint                   NOT NULL,
                                   email         varchar(255)             NOT NULL,
                                   invited_by_id bigint                   NOT NULL,
                                   status        varchar(20)              NOT NULL,
                                   created_at    timestamp with time zone NOT NULL,
                                   CONSTRAINT fk_group_invitations_group
                                       FOREIGN KEY (group_id) REFERENCES expense_group (id),
                                   CONSTRAINT fk_group_invitations_invited_by
                                       FOREIGN KEY (invited_by_id) REFERENCES users (id),
                                   CONSTRAINT chk_group_invitations_status
                                       CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED'))
);

-- at most one open invitation per group and e-mail; declined ones do not block a new invite
CREATE UNIQUE INDEX uq_group_invitations_pending
    ON group_invitations (group_id, email) WHERE status = 'PENDING';
CREATE INDEX idx_group_invitations_group_id ON group_invitations (group_id);
CREATE INDEX idx_group_invitations_email ON group_invitations (email);
CREATE INDEX idx_group_invitations_invited_by_id ON group_invitations (invited_by_id);
